import fs from 'node:fs';
import assert from 'node:assert/strict';
const plan=JSON.parse(fs.readFileSync('plan.json','utf8'));
assert.equal(plan.fixtures.length,12);
assert.equal(plan.fixtures.filter(f=>f.kind==='H').reduce((n,f)=>n+f.qty,0),800);
assert.equal(plan.fixtures.filter(f=>f.kind==='D').reduce((n,f)=>n+f.qty,0),1200);
assert.ok(Math.abs(plan.main_width_m-plan.meeting_width_m-plan.partition_m-16)<1e-10);
for(const file of ['app.js','style.css','plan.json','vendor/three.module.js','vendor/OrbitControls.js','vendor/RoomEnvironment.js','vendor/TessellateModifier.js','vendor/LICENSE-three.txt'])assert.ok(fs.statSync(''+file).size>0,file);
const script=fs.readFileSync('app.js','utf8');
assert.ok(script.includes("closest('button[data-view]')"),'Viewport dataset must not reset views on generic clicks');
assert.ok(!script.includes("closest('[data-view]')"));
const html=fs.readFileSync('index.html','utf8');
for(const id of ['toggle-dims','toggle-labels','toggle-antennas','toggle-roof','capture','view-nav','help-dialog'])assert.ok(html.includes(`id="${id}"`));
assert.ok(!html.includes('https://cdn.'));
assert.equal(plan.height_m,3.5,'the room clear height comes from revision R02');
assert.equal(plan.partition_glass,true,'the meeting/showroom partition is frosted glass');
assert.equal(plan.doors.length,6,'the model contains all six openings');
assert.equal(plan.doors.filter(d=>d.type==='automatic').length,1,'the showroom entrance is automatic sliding');
assert.equal(plan.doors.filter(d=>d.type==='swing').length,5,'all remaining doors are operable swing doors');
for(const id of ['toggle-roof','wall-visibility','door-controls'])assert.ok(html.includes(`id="${id}"`),`missing control ${id}`);
assert.ok(script.includes('frosted'),'the room divider uses an opaque frosted material');
assert.ok(script.includes('doorControllers'),'door panels have an interactive controller');
console.log('PASS: fixed local dependencies, exact 16m width, 12 fixtures / 2000 garments, navigation regression and required controls.');
