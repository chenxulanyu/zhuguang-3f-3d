import fs from 'node:fs';
import assert from 'node:assert/strict';
const plan=JSON.parse(fs.readFileSync('plan.json','utf8'));
assert.equal(plan.fixtures.length,12);
assert.equal(plan.fixtures.filter(f=>f.kind==='H').reduce((n,f)=>n+f.qty,0),800);
assert.equal(plan.fixtures.filter(f=>f.kind==='D').reduce((n,f)=>n+f.qty,0),1200);
assert.ok(Math.abs(plan.showroom_width_m-(plan.main_width_m-plan.meeting_width_m-plan.partition_m))<1e-10);
for(const file of ['app.js','style.css','plan.json','vendor/three.module.js','vendor/OrbitControls.js','vendor/RoomEnvironment.js','vendor/TessellateModifier.js','vendor/LICENSE-three.txt'])assert.ok(fs.statSync(''+file).size>0,file);
const script=fs.readFileSync('app.js','utf8');
assert.ok(script.includes("closest('button[data-view]')"),'Viewport dataset must not reset views on generic clicks');
assert.ok(!script.includes("closest('[data-view]')"));
const html=fs.readFileSync('index.html','utf8');
for(const id of ['toggle-dims','toggle-labels','toggle-antennas','toggle-roof','capture','view-nav','help-dialog'])assert.ok(html.includes(`id="${id}"`));
assert.ok(!html.includes('https://cdn.'));
assert.equal(plan.height_m,3.5,'the room clear height comes from revision R09');
assert.equal(plan.partition_glass,true,'the meeting/showroom partition is frosted glass');
assert.equal(plan.revision,'R09');
assert.equal(plan.meeting_width_m,4);
assert.equal(plan.meeting_table.w,1.1);
assert.ok(Math.abs(plan.meeting_table.x+plan.meeting_table.w/2-plan.meeting_width_m/2)<1e-6,'meeting table must be centered across the room');
assert.ok(Math.abs(plan.meeting_table.y+plan.meeting_table.h/2-plan.depth_m/2)<1e-6,'meeting table must be centered along the room');
assert.ok(!plan.doors.some(d=>d.id==='M01'),'no corridor-side meeting room door');
assert.equal(plan.doors.length,5,'the model contains all five openings');
assert.equal(plan.doors.filter(d=>d.type==='automatic').length,1,'the showroom entrance is automatic sliding');
assert.equal(plan.doors.filter(d=>d.type==='swing').length,4,'all remaining doors are operable swing doors');
assert.equal(plan.doors.find(d=>d.id==='M04').width,.9,'the warehouse uses the original single door');
assert.equal(plan.checkout_counter.w,.8);
assert.equal(plan.checkout_counter.h,1.2);
assert.equal(plan.checkout_counter.staff_clearance,.7,'the cashier bay is 700mm');
assert.equal(plan.checkout_counter.customer_side,'west, facing counter');
const cash=plan.checkout_counter;
assert.ok(Math.abs(plan.main_width_m-cash.x-cash.w-cash.staff_clearance)<.001,'cashier has 700mm between counter and wall');
assert.ok(cash.y+cash.h<plan.fitting_block[1]-.7,'cashier access remains open beside fitting rooms');
const warehouseDoor=plan.doors.find(d=>d.id==='M04'),warehouseWall=plan.partitions.find(p=>p.id==='Q06');
assert.equal(warehouseDoor.axis,'x');
assert.ok(warehouseWall.openings.includes('M04'));
assert.ok(Math.abs(warehouseDoor.fixed-warehouseWall.z)<1e-6);
assert.ok(warehouseDoor.start>=warehouseWall.x&&warehouseDoor.end<=warehouseWall.x+warehouseWall.w);
for(const f of plan.fixtures){
 assert.ok(f.x>=plan.meeting_width_m+plan.partition_m&&f.x+f.w<=plan.fitting_block[0],'fixtures stay in the showroom');
 assert.ok(f.x+f.w<=cash.x||cash.x+cash.w<=f.x||f.y+f.h<=cash.y||cash.y+cash.h<=f.y,'fixtures must not overlap checkout');
}
assert.equal(plan.antennas.filter(a=>a[4]==='展示厅'&&a[3]===4).length,4);
for(const id of ['toggle-roof','wall-visibility','door-controls'])assert.ok(html.includes(`id="${id}"`),`missing control ${id}`);
assert.ok(script.includes('frosted'),'the room divider uses an opaque frosted material');
assert.ok(script.includes('doorControllers'),'door panels have an interactive controller');
console.log('PASS: R09 geometry, 12 fixtures / 2000 garments, single warehouse door, checkout cashier bay, navigation regression and required controls.');
